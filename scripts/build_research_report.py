def make_table(spec):
    widths = [r * AVAIL_W for r in spec["widths"]]
    assert abs(sum(widths) - AVAIL_W) < 1.0, "colWidths must equal available width"
    compact = spec.get("compact", False)
    fs = 8.3 if compact else 9
    th = ParagraphStyle("THx", parent=S["th"], fontSize=fs, leading=fs + 3)
    td = ParagraphStyle("TDx", parent=S["td"], fontSize=fs, leading=fs + 3.5)
    tdu = ParagraphStyle("TDUx", parent=td, wordWrap="CJK")
    header = [Paragraph("<b>%s</b>" % content_sanitize(h), th) for h in spec["header"]]
    rows = [header]
    for row in spec["rows"]:
        cells = []
        for cell in row:
            txt = content_sanitize(str(cell))
            style = tdu if txt.startswith("http") else td
            cells.append(Paragraph(txt, style))
        rows.append(cells)
    pad = 3.5 if compact else 5
    t = Table(rows, colWidths=widths, hAlign="CENTER", repeatRows=1)
    style_cmds = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), pad),
        ("BOTTOMPADDING", (0, 0), (-1, -1), pad),
    ]
    for i in range(1, len(rows)):
        style_cmds.append(("BACKGROUND", (0, i), (-1, i),
                           TABLE_ROW_ODD if i % 2 == 1 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style_cmds))
    out = [Spacer(1, 10), t]
    if spec.get("caption"):
        out += [Paragraph(content_sanitize(spec["caption"]), S["caption"])]
    out += [Spacer(1, 8)]
    return out

def make_imgpair(left, right, lcap, rcap):
    col = AVAIL_W * 0.5 - 6
    i1 = fit_image(left, col - 12, 300)
    i2 = fit_image(right, col - 12, 300)
    cap_l = Paragraph(content_sanitize(lcap), S["caption"])
    cap_r = Paragraph(content_sanitize(rcap), S["caption"])
    t = Table([[i1, i2], [cap_l, cap_r]], colWidths=[col, col], hAlign="CENTER")
    t.setStyle(TableStyle([
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, 0), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("LEFTPADDING", (0, 0), (-1, -1), 2),
        ("RIGHTPADDING", (0, 0), (-1, -1), 2),
    ]))
    return [Spacer(1, 8)] + safe_keep_together([t]) + [Spacer(1, 8)]

def make_img(path, caption, max_h):
    img = fit_image(path, AVAIL_W * 0.92, max_h)
    img.hAlign = "CENTER"
    cap = Paragraph(content_sanitize(caption), S["caption"])
    return [Spacer(1, 8)] + safe_keep_together([img, cap]) + [Spacer(1, 8)]

